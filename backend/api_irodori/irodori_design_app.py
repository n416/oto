def _default_checkpoint() -> str:
    candidates = sorted(
        [
            *Path("../Irodori-TTS").glob("**/checkpoint_*.pt"),
            *Path("../Irodori-TTS").glob("**/checkpoint_*.safetensors"),
        ]
    )
    preferred = [
        path
        for path in candidates
        if "caption" in str(path).lower() or "voice_design" in str(path).lower()
    ]
    if preferred:
        return str(preferred[-1])
    if candidates:
        return str(candidates[-1])
    return "Aratako/Irodori-TTS-500M-v2-VoiceDesign"


