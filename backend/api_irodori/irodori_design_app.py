class IrodoriDesignRequest(BaseModel):
    checkpoint: str = "Aratako/Irodori-TTS-500M-v2-VoiceDesign"
    model_device: str = "cuda"
    model_precision: str = "bf16"
    codec_device: str = "cuda"
    codec_precision: str = "bf16"
    text: str
    caption: str = ""
    num_steps: int = 40
    num_candidates: int = 1
    seed_raw: str = ""
    seconds_raw: str = ""
    duration_scale: float = 1.0
    t_schedule_mode: str = "linear"
    sway_coeff: float = -1.0
    cfg_guidance_mode: str = "independent"
    cfg_scale_text: float = 2.0
    cfg_scale_caption: float = 4.0
    cfg_scale_raw: str = ""
    cfg_min_t: float = 0.5
    cfg_max_t: float = 1.0
    context_kv_cache: bool = True
    max_text_len_raw: str = ""
    max_caption_len_raw: str = ""
    truncation_factor_raw: str = ""
    rescale_k_raw: str = ""
    rescale_sigma_raw: str = ""
    lora_adapter_raw: str = ""

@app.get("/")
def api_root():
    return {"status": "ok"}

@app.post("/generate")
def api_generate(req: IrodoriDesignRequest):
    out_paths = _run_generation(
        checkpoint=req.checkpoint,
        model_device=req.model_device,
        model_precision=req.model_precision,
        codec_device=req.codec_device,
        codec_precision=req.codec_precision,
        text=req.text,
        caption=req.caption,
        num_steps=req.num_steps,
        num_candidates=req.num_candidates,
        seed_raw=req.seed_raw,
        seconds_raw=req.seconds_raw,
        duration_scale=req.duration_scale,
        t_schedule_mode=req.t_schedule_mode,
        sway_coeff=req.sway_coeff,
        cfg_guidance_mode=req.cfg_guidance_mode,
        cfg_scale_text=req.cfg_scale_text,
        cfg_scale_caption=req.cfg_scale_caption,
        cfg_scale_raw=req.cfg_scale_raw,
        cfg_min_t=req.cfg_min_t,
        cfg_max_t=req.cfg_max_t,
        context_kv_cache=req.context_kv_cache,
        max_text_len_raw=req.max_text_len_raw,
        max_caption_len_raw=req.max_caption_len_raw,
        truncation_factor_raw=req.truncation_factor_raw,
        rescale_k_raw=req.rescale_k_raw,
        rescale_sigma_raw=req.rescale_sigma_raw,
        lora_adapter_raw=req.lora_adapter_raw,
    )
    
    urls = []
    for path_str in out_paths:
        name = __import__("pathlib").Path(path_str).name
        urls.append(f"http://127.0.0.1:7861/outputs/voice/{name}")
    
    return {"urls": urls}

